"""Generate config/obix.yaml from the live NeoView point tree.

Scans one or more oBIX folders (recursively), and writes a `read:` map that
turns the BMS points into *pseudo-meters* on the gateway, one pseudo-meter per
scanned device ("--meter", else a slug of the folder). Each point becomes a
slugged point id, so the values land in the buffer's normalized_value table and
flow through the AI pipeline like any other reading.

    # list what WOULD be written, without touching the file
    .\\.venv\\Scripts\\python.exe scripts\\obix_map.py \\
        --folder /config/Drivers/BacnetNetwork/ENYECONTROLS/points --dry-run

    # write it (keeps a header, replaces read:, leaves write: empty)
    .\\.venv\\Scripts\\python.exe scripts\\obix_map.py \\
        --folder /config/Drivers/BacnetNetwork/ENYECONTROLS/points \\
        --folder /config/Drivers/BacnetNetwork/iEM3265_0020343063/points

Point values are NOT read here; only the tree is walked. Runs best with
OBIX_BASE_URL / OBIX_USERNAME / OBIX_PASSWORD set in .env.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from gateway.config import Settings  # noqa: E402
from gateway.obix import ObixClient, ObixError  # noqa: E402

HEADER = """\
# obix.yaml - explicit map between the gateway model and NeoView (Niagara 4).
#
# Generated by scripts/obix_map.py. Hrefs are relative to OBIX_BASE_URL.
# `read` turns each NeoView device into a pseudo-meter on the gateway; values
# land in normalized_value and flow through the AI pipeline.
#
# read:  <pseudo_meter_id>:
#          <point_id>: <oBIX point href>
# write: <meter_id>:
#          <finding_key>: <oBIX writable point href>
#        (create writable points under /config/Drivers/ObixNetwork/exports)

"""


def decode_name(name: str) -> str:
    """Decode Niagara ``$XX`` hex escapes in a path segment."""
    return re.sub(r"\$([0-9A-Fa-f]{2})", lambda m: chr(int(m.group(1), 16)), name)


def slug_name(name: str) -> str:
    decoded = re.sub(r"\$([0-9A-Fa-f]{2})", lambda m: chr(int(m.group(1), 16)), name)
    return re.sub(r"[^a-z0-9]+", "_", decoded.lower()).strip("_")


def scan(client, folder: str, depth: int, rel: str = ""):
    """Yield (point_id, href) for every non-folder ref under ``folder``."""
    for ref in client.list_refs(folder):
        if not ref.href:
            continue
        child_rel = f"{rel}_{ref.name}" if rel else ref.name
        is_folder = "folder" in (ref.is_type or "").lower()
        if is_folder and depth > 1:
            yield from scan(client, f"{folder.rstrip('/')}/{ref.href}", depth - 1, child_rel)
        elif not is_folder:
            yield slug_name(child_rel), f"{folder.rstrip('/')}/{ref.href}"


def meter_slug(folder: str) -> str:
    parts = [p for p in folder.strip("/").split("/") if p]
    if parts and parts[-1].lower() == "points":
        parts = parts[:-1]
    name = parts[-1] if parts else "bms"
    return "bms_" + slug_name(name)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--folder", action="append", required=True,
                        help="oBIX folder to scan (repeatable)")
    parser.add_argument("--meter", action="append", default=[],
                        help="pseudo-meter id per --folder (default: derived)")
    parser.add_argument("--depth", type=int, default=3,
                        help="folder recursion depth (default: 3)")
    parser.add_argument("--base-url", default=None)
    parser.add_argument("--username", default=None)
    parser.add_argument("--password", default=None)
    parser.add_argument("--auth", default=None, choices=["auto", "basic", "scram"])
    parser.add_argument("--no-verify-tls", action="store_true")
    parser.add_argument("--out", default="config/obix.yaml")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    settings = Settings()
    base_url = args.base_url or settings.obix_base_url
    if not base_url:
        print("OBIX_BASE_URL is empty - set it in .env or pass --base-url")
        return 2

    client = ObixClient(
        base_url,
        username=(args.username if args.username is not None else settings.obix_username) or None,
        password=(args.password if args.password is not None else settings.obix_password) or None,
        timeout=settings.obix_timeout_seconds,
        verify_tls=not (args.no_verify_tls or not settings.obix_verify_tls),
        auth=args.auth or settings.obix_auth,
    )

    lines = ["read:"]
    total = 0
    for i, folder in enumerate(args.folder):
        meter = args.meter[i] if i < len(args.meter) else meter_slug(folder)
        entries = [(pid, href) for pid, href in scan(client, folder, args.depth)]
        # de-duplicate point ids within a meter (keep the first)
        seen: set[str] = set()
        unique = []
        for pid, href in entries:
            if pid in seen:
                continue
            seen.add(pid)
            unique.append((pid, href))
        total += len(unique)
        print(f"{folder} -> {meter}: {len(unique)} point(s)")
        lines.append(f'  "{meter}":')
        for pid, href in unique:
            lines.append(f'    {pid}: "{href}"')
    lines.append("")
    lines.append("write: {}")
    text = HEADER + "\n".join(lines) + "\n"

    if args.dry_run:
        print(f"\n--- would write {args.out} ({total} points) ---")
        print(text)
        return 0

    out = ROOT / args.out
    out.write_text(HEADER + "\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {out} ({total} points)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
